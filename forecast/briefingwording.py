def render(source: str | None = None) -> dict[str, list[list[str]]]:
    node = shutil.which("node")
    if node is None:
        raise RuntimeError("node is not installed")
    source = PAGE.read_text(encoding="utf-8") if source is None else source
    env = dict(os.environ, TZ="America/Los_Angeles", LANG="en_US.UTF-8", LC_ALL="en_US.UTF-8")
    got = subprocess.run([node, "-e", script(source)], capture_output=True, text=True,
                         env=env, check=True)
    return json.loads(got.stdout)


def permutations(rendered: dict[str, list[list[str]]]) -> str:
    parts = [MARKER, ""]
    for cid, title, _ in CASES:
        lines = [line for head, body in rendered[cid] for line in (head, body, "")]
        parts += [f"### {cid}: {title}", "", "```text", *(lines[:-1] or ["(no Briefing: the fold is not drawn)"]),
                  "```", ""]
    return "\n".join(parts)


def build(doc: str, rendered) -> str:
    head = doc[:doc.index(MARKER)] if MARKER in doc else doc.rstrip("\n") + "\n\n"
    return head + permutations(rendered)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the doc is out of date")
    args = parser.parse_args(argv)
    doc = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
    want = build(doc, render())
    if args.check:
        if want != doc:
            print(f"{DOC.relative_to(ROOT)} is out of date: run python -m forecast.briefingwording")
            return 1
        return 0
    DOC.write_text(want, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}: {len(CASES)} cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
