TEXT = r"""
const text = (html) => html
  .replace(/ <span class="unit">(?!\()/g, " ")
  .replace(/<a href="([^"]+)"[^>]*>([^<]+)<\/a>/g, "[$2]($1)")
  .replace(/<svg class="storm-sym" data-kind="([a-z-]+)"[^]*?<\/svg>/g, (_, k) => ` {${k.replace("-", " ")} symbol}`)
  .replace(/<[^>]+>/g, "").replace(/\u00a0/g, " ").trim();
const words = (B, readAt) => ({line: B && B.available ? text(briefIssue(B, readAt)) : null,
                               entries: briefingEntries(B).map((e) => [text(e.head), text(e.body)])});
"""


def _node(script: str) -> dict:
    node = shutil.which("node")
    if node is None:
        raise RuntimeError("node is not installed")
    env = dict(os.environ, TZ="America/Los_Angeles", LANG="en_US.UTF-8", LC_ALL="en_US.UTF-8")
    got = subprocess.run([node, "-e", script], capture_output=True, text=True, env=env, check=True)
    return json.loads(got.stdout)


def render(source: str | None = None) -> dict[str, dict]:
    source = PAGE.read_text(encoding="utf-8") if source is None else source
    cases = json.dumps([[cid, block] for cid, _, block in CASES])
    return _node(code(source) + TEXT + f"""
const out = {{}};
for (const [id, B] of {cases}) out[id] = words(B, Date.parse("{READ_AT}"));
console.log(JSON.stringify(out));
""")


def render_issue(issue: dict, source: str | None = None) -> dict:
    """The words the page prints for one issue, read on its own day, as
    `{"line": …, "entries": [[head, body], …]}`."""

    source = PAGE.read_text(encoding="utf-8") if source is None else source
    return _node(code(source) + TEXT + f"""
const B = {json.dumps(issue)};
console.log(JSON.stringify(words(B, Date.parse(B.issued_utc))));
""")


def permutations(rendered: dict[str, dict]) -> str:
    parts = [MARKER, ""]
    for cid, title, _ in CASES:
        got = rendered[cid]
        lines = [line for head, body in got["entries"] for line in (head, body, "")]
        body = [f"[{got['line']}]", "", *lines[:-1]] if got["line"] and lines else ["(no Briefing: the fold is not drawn)"]
        parts += [f"### {cid}: {title}", "", "```text", *body, "```", ""]
    return "\n".join(parts)


