#: Each sentence's number in the list, by its entry.
PREFIX = {"Overview": "OV", "Swell": "SW", "Tide": "TI", "Wind": "WI", "Watching": "WA"}
#: Cases that exist for the fold's line alone: their entries are another
#: case's made-up numbers read on the wrong day.
LINE_ONLY = {"Y1"}


def split_sentences(body: str) -> list[str]:
    import re

    return [x for x in re.split(r"(?<=[.])\s+(?=[A-Z])", body) if x]


def sentences(rendered: dict[str, dict]) -> str:
    """Each distinct sentence, by entry, first seen first, with its cases."""

    seen: dict[str, dict[str, list[str]]] = {"line": {}, **{e: {} for e in ENTRIES}}
    for cid, _, _ in CASES:
        got = rendered[cid]
        if got["line"]:
            seen["line"].setdefault(got["line"], []).append(cid)
        for head, body in ([] if cid in LINE_ONLY else got["entries"]):
            for sentence in split_sentences(body):
                seen[head].setdefault(sentence, []).append(cid)
    every = [cid for cid, _, _ in CASES if rendered[cid]["entries"] and cid not in LINE_ONLY]
    tag = lambda ids: "every case" if ids == every else ", ".join(ids)
    parts = [SENTENCES_HEAD, "## The fold's line", ""]
    parts += [f"- {line}  ({tag(ids)})" for line, ids in seen["line"].items()]
    for entry in ENTRIES:
        parts += ["", f"## {entry}", ""]
        for k, (sentence, ids) in enumerate(seen[entry].items(), 1):
            parts += [f"{PREFIX[entry]}{k}. {sentence}  ({tag(ids)})", ""]
    parts += ["## The cases", ""]
    parts += [f"- **{cid}**: {title}" + (" (its line only)" if cid in LINE_ONLY else "") for cid, title, _ in CASES]
    return "\n".join(parts).rstrip() + "\n"


def build(doc: str, rendered) -> str:
    head = doc[:doc.index(MARKER)] if MARKER in doc else doc.rstrip("\n") + "\n\n"
    return head + permutations(rendered)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the doc is out of date")
    args = parser.parse_args(argv)
    doc = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
    rendered = render()
    want = {DOC: build(doc, rendered), SENTENCES: sentences(rendered)}
    if args.check:
        stale = [p for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run python -m forecast.briefingwording")
        return 1 if stale else 0
    for p, text in want.items():
        p.write_text(text, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)} and {SENTENCES.relative_to(ROOT)}: {len(CASES)} cases")
    return 0


