"""Every wording the LIVE Briefing can show, rendered by the page's own code.

    python -m forecast.briefingwording            # rewrite the permutations
    python -m forecast.briefingwording --check    # exit 1 if they are out of date

`docs/briefing_wording.md` states the formula: one entry per story, each a
heading over one paragraph, each paragraph a fixed run of slots, a slot with
no value dropped with its joining words. Its last section shows every
permutation, and this writes it: the Briefing functions are lifted out of
`app/forecast.html` and run in Node on one made-up `briefing.json` per
branch, so the examples are what the page prints, never typed.
`tests/test_briefingwording.py` pins that the file is this output.

The numbers in the cases are made up; only the wording is under review.
Times are Pacific, the reader's zone at these beaches, and the reader's
clock stands at `READ_AT`.
"""

