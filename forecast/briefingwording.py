def _lift(source: str, start: str, end: str) -> str:
    a = source.index(start)
    return source[a:source.index(end, a) + len(end)]


def _between(source: str, start: str, stop: str) -> str:
    a = source.index(start)
    return source[a:source.index(stop, a)]


