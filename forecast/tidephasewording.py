BLOCK = {"station": tp.STATION, "analysis": "2017–2021", "diurnal_age_h": 14.4}


def _lift(source: str, start: str, end: str) -> str:
    a = source.index(start)
    return source[a:source.index(end, a) + len(end)]


def script(source: str, cases: list) -> str:
    code = "\n".join([
        _lift(source, "const FT_PER_M = ", ";"),
        # The Units setting and the formatters built on it, as one block.
        source[source.index("let UNITS = "):source.index("\n// Display-only shortenings")],
        source[source.index("const COAST_TZ = "):source.index("// Whether the phase fold is open")],
    ])
    return code + f"""
const out = {{}};
for (const [id, block, s] of {json.dumps(cases)}) {{
  out[id] = tidePhaseText(block, s, true).map(([h, p]) => [h, p
    .replace(/ <span class="unit">/g, " ").replace(/<[^>]+>/g, "")]);
}}
console.log(JSON.stringify(out));
"""


def cases(data_dir: Path = tp.DEFAULT_DATA_DIR) -> list:
    out = []
    for cid, at, _ in ARCHIVE:
        c = archive_case(data_dir, at)
        out.append([cid, c["block"], c["summary"]])
    for cid, _, s in MADE_UP:
        out.append([cid, BLOCK, s])
    return out


def render(source: str | None = None, data_dir: Path = tp.DEFAULT_DATA_DIR) -> dict[str, list[list[str]]]:
    node = shutil.which("node")
    if node is None:
        raise RuntimeError("node is not installed")
    source = PAGE.read_text(encoding="utf-8") if source is None else source
    env = dict(os.environ, TZ="America/Los_Angeles", LANG="en_US.UTF-8", LC_ALL="en_US.UTF-8")
    got = subprocess.run([node, "-e", script(source, cases(data_dir))], capture_output=True,
                         text=True, env=env, check=True)
    return json.loads(got.stdout)


def _quote(paras) -> list[str]:
    """Each paragraph as the page lays it out: its bold heading on one line,
    its body on the next."""

    out = []
    for head, body in paras:
        out += [f"> **{head}**  ", f"> {body}", ">"]
    out[-1] = ""
    return out


def section(rendered: dict[str, list[str]]) -> str:
    parts = [MARKER, ""]
    for cid, at, title in ARCHIVE:
        parts += [f"### As of {cid}, noon: {title}", "", "From the archive as it stood then.", ""]
        parts += _quote(rendered[cid])
    for cid, title, _ in MADE_UP:
        parts += [f"### {cid}: {title}", "", "Made up, to reach this branch.", ""]
        parts += _quote(rendered[cid])
    return "\n".join(parts)


def build(doc: str, rendered: dict[str, list[str]]) -> str:
    head = doc[:doc.index(MARKER)] if MARKER in doc else doc.rstrip("\n") + "\n\n"
    return head + section(rendered)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the doc is out of date")
    args = parser.parse_args(argv)
    doc = DOC.read_text(encoding="utf-8")
    want = build(doc, render())
    if args.check:
        if want != doc:
            print(f"{DOC.relative_to(ROOT)} is out of date: run python -m forecast.tidephasewording")
            return 1
        return 0
    DOC.write_text(want, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}: {len(ARCHIVE) + len(MADE_UP)} cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
