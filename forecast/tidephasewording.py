"""Every wording the Tide card's phase fold can show, rendered by the page's own code.

    python -m forecast.tidephasewording            # rewrite the cases
    python -m forecast.tidephasewording --check    # exit 1 if they are out of date

`docs/tide_phase_wording.md` states the formula (owner's request,
2026-10-11): three paragraphs, each a fixed run of slots, a slot with no value
dropped with its joining words. Its last section shows the cases, and this
writes them: the page's phase functions are lifted out of `app/forecast.html`
and run in Node on summaries built by `forecast.tidephase` -- four from the
archive as it stood on those dates (the constants and the turns seen by
then), and made-up ones for every branch those four do not reach.
`tests/test_tidephasewording.py` pins that the file is this output.
"""

