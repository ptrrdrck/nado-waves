def turns_seen(data_dir: Path, by: datetime) -> list[dict]:
    """The card's turns as they stood at `by`: every turn first seen by then,
    carried to the coast with the departure measured by then."""

    path = Path(data_dir) / "tide" / f"{tp.STATION}_turns.csv"
    rows = {}
    for r in csv.DictReader(path.open()):
        if tp._parse(r["first_seen_utc"]) <= by:
            rows[r["time_utc"]] = r
    departure, _ = anomaly(data_dir, by)
    return [coast_turn(Turn(r["time_utc"], float(r["height_m"]), r["event"]), departure).as_dict()
            for _, r in sorted(rows.items())]


def archive_case(data_dir: Path, at: datetime) -> dict:
    block = tp.block(data_dir, [at.astimezone(tp.LOCAL_TZ).date()], turns_seen(data_dir, at), now=at)
    return {"block": {k: v for k, v in block.items() if k != "days"},
            "summary": next(iter(block["days"].values()))}


